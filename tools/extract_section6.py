#!/usr/bin/env python3
"""Build Section 6's page map from the source architecture.

    python3 tools/extract_section6.py            # dry run, prints the shape
    python3 tools/extract_section6.py --write    # writes pages_6.json

Committed for the reason decision 027 committed the Section 5 extractor:
pages_4.json was generated by a script in a scratchpad directory, the container
was reclaimed, and the map can no longer be re-derived or checked against the
source. A test holds this file and pages_6.json in step.

## What this can and cannot build

The source enumerates numbered sub pages for chapters 6.1 to 6.8 only, which is
Part A, ACL disorders. Every chapter from 6.9 to 6.156 is a bare chapter line
with nothing beneath it. That is not a defect in the source: Part 1's conventions
say so in as many words, that a chapter listed without numbered sub pages, which
is "common from Section 6 onwards", publishes as a single page carrying the
chapter id.

So this tool builds the 37 pages the source enumerates and refuses to invent the
rest. It prints what it skipped, with the count, so the gap is visible on every
run rather than discoverable by reading the output.

Part 1 estimates Section 6 at 500 to 700 pages across 156 chapters. Building
every bare chapter as a single page would give 185, which is the floor rather
than the map, and the ids would carry two components where every published page
on this site carries three. Neither of those is this tool's call to make.
"""

import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs",
                   "KneeSchool_Sections_1_to_15_Full_Architecture.txt")
PART1 = os.path.join(ROOT, "docs",
                     "KneeSchool_Master_Publishing_Architecture_Part1.md")
OUT = os.path.join(ROOT, "pipeline", "config", "architecture", "pages_6.json")

START = "SECTION 6: CONDITIONS LIBRARY"
STOP = "SECTION 7: SURGICAL ACADEMY"

SECTION = collections.OrderedDict([("id", "6"), ("name", "Conditions Library")])

# Part 1 section 3: every tier set in Part 1 is an editorial default awaiting
# Editor in Chief sign off, and the source states none for Section 6 at all. It
# does state, in its own overview, that every condition should be structured
# into Patient, Medical Student, MRCS, FRCS and Fellowship versions. Junior and
# Consultant are added to reach the site's seven, matching the one Section 6
# page that already existed before any map did. This is the same weak derivation
# decisions 024 and 027 record for Sections 4 and 5, and it is labelled as such.
TIERS = ["junior", "patient", "medical_student", "mrcs", "frcs", "fellowship",
         "consultant"]

PART = re.compile(r"^PART ([A-Z]): (.+)$")
CHAPTER = re.compile(r"^Chapter (6\.\d+) (.+)$")
LEAF = re.compile(r"^(6\.\d+\.\d+) (.+)$")

BASE_MNC = [
    "Structure level anatomy (owned by Section 2)",
    "Biomechanics beyond what the condition depends on (owned by Section 3)",
    "Examination technique and interpretation (owned by Section 4)",
    "Imaging acquisition and appearance (owned by Section 5)",
    "Operative technique (owned by Section 7)",
    "Rehabilitation protocol detail (owned by Section 8)",
]

# The scope sentence is the title restated, which is the most this process can
# honestly supply without Part 3. The clause after the title is chosen by what
# the chapter is for: "Epidemiology, as it presents and is managed" is not true
# of anything, and chapter 6.1 and chapter 6.6 are both about a subject rather
# than about a presentation.
SCOPE_CLAUSE = [
    (("6.1",), "as the clinician needs to understand it."),
    (("6.6",), "as it bears on the female athlete's risk."),
]
SCOPE_DEFAULT = "as it presents and is managed."


def scope_for(chapter, title):
    clause = SCOPE_DEFAULT
    for chapters, c in SCOPE_CLAUSE:
        if chapter in chapters:
            clause = c
    # "What is the ACL?, as the clinician needs to understand it" is the one
    # title in the section that already ends in its own punctuation.
    if title.endswith(("?", "!", ".")):
        return "%s %s" % (title, clause[0].upper() + clause[1:])
    return "%s, %s" % (title, clause)


def part_name(raw):
    """"PART A: ACL DISORDERS" gives "ACL Disorders", not "Acl Disorders".

    str.title() lowercases every letter after the first of a word, which turns
    every acronym in the part list into a word: ACL, PCL, OA. The source writes
    part names in capitals throughout, so a short all capital word is an
    acronym and is left alone.
    """
    return " ".join(w if w.isupper() and len(w) <= 4 else w.title()
                    for w in raw.split())


def spiral_deeper():
    """The deeper step after each Section 6 chapter, from Part 1's spiral map.

    The map is the architecture's own statement of what follows what, so the
    deeper pages come from it rather than from a judgement about which surgery
    chapter belongs with which condition. The ACL row's step after 6.1 to 6.8 is
    7.20 to 7.31. Chapter 6.6 appears a second time, in the women's knee health
    row, whose next step is 8.99 and 8.100, so it carries both.
    """
    with open(PART1, encoding="utf-8") as fh:
        text = fh.read()
    table = text.split("## 5. Spiral Linkage Map", 1)[1].split("\n## ", 1)[0]
    deeper = collections.defaultdict(list)
    for row in table.splitlines():
        if not row.startswith("|") or row.startswith("|---"):
            continue
        cells = [c.strip() for c in row.strip("|").split("|")]
        if len(cells) != 2 or cells[0] == "Topic":
            continue
        steps = [s.strip() for s in cells[1].split("→")]
        for i, step in enumerate(steps[:-1]):
            ids = re.findall(r"\b6\.\d+(?:\.\d+)*\b", step)
            if not ids:
                continue
            nxt = re.findall(r"\b\d+\.\d+(?:\.\d+)*\b", steps[i + 1])
            # "6.1 to 6.8" names a range, so every chapter inside it takes the
            # same deeper step. A row naming single chapters takes them as they
            # are.
            covered = []
            if " to " in step and len(ids) == 2:
                lo, hi = (int(x.split(".")[1]) for x in ids)
                covered = ["6.%d" % n for n in range(lo, hi + 1)]
            else:
                covered = ids
            for c in covered:
                for n in nxt:
                    if n not in deeper[c]:
                        deeper[c].append(n)
    return deeper


def source_lines():
    with open(SRC, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    begin = next(i for i, l in enumerate(lines) if l.strip() == START)
    finish = next(i for i, l in enumerate(lines) if l.strip().startswith(STOP))
    return lines[begin + 1:finish]


def build():
    """Returns (pages, skipped), skipped being the chapters with no sub pages."""
    deeper = spiral_deeper()
    part = None
    chapter = None
    chapters = collections.OrderedDict()
    for line in source_lines():
        line = line.rstrip()
        m = PART.match(line)
        if m:
            part = collections.OrderedDict([("letter", m.group(1)),
                                            ("name", part_name(m.group(2)))])
            continue
        m = CHAPTER.match(line)
        if m:
            chapter = m.group(1)
            chapters[chapter] = {"name": m.group(2), "part": part, "leaves": []}
            continue
        m = LEAF.match(line)
        if m and chapter:
            chapters[chapter]["leaves"].append((m.group(1), m.group(2)))

    pages = []
    skipped = []
    for chapter, data in chapters.items():
        if not data["leaves"]:
            skipped.append((chapter, data["name"]))
            continue
        ids = [i for i, _ in data["leaves"]]
        for page_id, title in data["leaves"]:
            pages.append(collections.OrderedDict([
                ("page_id", page_id),
                ("title", title),
                ("section", dict(SECTION)),
                ("chapter", collections.OrderedDict([("id", chapter),
                                                     ("name", data["name"])])),
                ("part", dict(data["part"])),
                ("tiers_required", list(TIERS)),
                ("scope", scope_for(chapter, title)),
                ("siblings", [i for i in ids if i != page_id]),
                ("deeper_pages", sorted(deeper.get(chapter, []))),
                ("must_not_cover", BASE_MNC + [
                    "Another condition's presentation or management (owned per "
                    "chapter by 6.1 to 6.156)"]),
                ("page_type", "condition"),
                # Part 1 calls Section 6 the clinical core, and the ACL row is
                # the most referenced chain in the spiral map. Everything this
                # tool can build is on it.
                ("priority", "high"),
            ]))
    return pages, skipped


def main():
    pages, skipped = build()
    by_chapter = collections.Counter(p["chapter"]["id"] for p in pages)
    for chapter in sorted(by_chapter, key=lambda c: int(c.split(".")[1])):
        name = next(p["chapter"]["name"] for p in pages
                    if p["chapter"]["id"] == chapter)
        print("  %-6s %-32s %d" % (chapter, name, by_chapter[chapter]))
    print("\n%d pages across %d chapters" % (len(pages), len(by_chapter)))
    print("%d chapters carry no numbered sub pages in the source and are not "
          "built:" % len(skipped))
    print("  %s to %s" % (skipped[0][0], skipped[-1][0]))
    if "--write" in sys.argv:
        with open(OUT, "w", encoding="utf-8") as fh:
            json.dump(pages, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
        print("\nwritten to %s" % OUT)
    else:
        print("\ndry run; pass --write to write %s" % OUT)


if __name__ == "__main__":
    main()
